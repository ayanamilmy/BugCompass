def set_language(language: str) -> None:
    global _LANGUAGE
    _LANGUAGE = "en" if str(language).lower().startswith("en") else "zh"


def get_language() -> str:
    return _LANGUAGE


def tr(text: str) -> str:
    """查表翻译；英文模式下未收录的键原样返回中文。"""
    if _LANGUAGE == "en":
        return EN.get(text, text)
    return text

